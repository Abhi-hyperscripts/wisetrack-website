#!/usr/bin/env python3
"""Generate assets/palettes.css from the token registry and the palette list in palette_lib.

    python3 tools/build-palettes.py

Each palette gets one html[data-palette="<id>"] block defining every token (and its space-
separated RGB triplet where the site uses the colour with an alpha). The first palette is
also written on :root, so a page with no attribute renders Curd & Sindoor. The swatch block
at the end gives site.js the list of palettes, their names and three preview colours.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from palette_lib import *

reg = load_registry()
order = sorted(reg.items(), key=lambda kv: (kv[1]['family'], kv[1]['name']))
out = ['/* Generated by tools/build-palettes.py — edit tools/palette_lib.py, not this file. */', '']
for i, pal in enumerate(PALETTES):
    sel = ':root, html[data-palette="%s"]' % pal['id'] if i == 0 else 'html[data-palette="%s"]' % pal['id']
    out.append('%s {' % sel)
    for h, v in order:
        c = '#' + h if i == 0 else retint(h, v['family'], pal)
        line = '  --%s: %s;' % (v['name'], c)
        if v['rgb']: line += ' --%s-rgb: %s;' % (v['name'], hex_to_rgb_triplet(c))
        out.append(line)
    out.append('}')
    out.append('')

# swatches for the picker: paper, accent, secondary (light theme values) and the dark paper
def tok(h, pal): return '#' + h if pal is PALETTES[0] else retint(h, family_of(h), pal)
out.append(':root { --palette-list: "%s"; }' % ','.join(p['id'] for p in PALETTES))
for pal in PALETTES:
    out.append('.pal-sw[data-p="%s"] { --pal-name: "%s"; --pal-paper: %s; --pal-ink: %s; --pal-accent: %s; --pal-second: %s; }' % (
        pal['id'], pal['name'], tok('f8f3ec', pal), tok('2a0810', pal), tok('d8261c', pal), tok('b8903f', pal)))
path = os.path.join(ROOT, 'assets', 'palettes.css')
open(path, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('palettes.css written: %d bytes, %d palettes x %d tokens' % (os.path.getsize(path), len(PALETTES), len(reg)))
