#!/usr/bin/env python3
"""Point every TEXT use of an accent token at its ink twin (see palette_lib.ink).

    python3 tools/apply-ink.py

- CSS (styles.css, the home/method scene sources, page <style> blocks): `color`,
  `-webkit-text-fill-color` and `caret-color` declarations that use an accent token, or an alias
  of one (--violet, --cyan, ...), switch to the ink variant. Every alias definition gains an
  --ink-<alias> sibling in the same block, so theme-dependent aliases stay theme-dependent.
- Tailwind: a generated `textColor` block mirrors `colors` with accent tokens swapped for ink,
  so text-indigo / text-cyan-500 read on every palette while bg-indigo keeps the brand fill.
Idempotent.
"""
import glob, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from palette_lib import ROOT, INK_FAMILIES

os.chdir(ROOT)
FAM = '|'.join(INK_FAMILIES)
TOK = r'(?:%s)-\d+[a-z]?' % FAM

def alias_defs(css):
    return dict(re.findall(r'(--[a-z][a-z0-9-]*)\s*:\s*var\(--(%s)\)' % TOK, css))

def css_ink(css, aliases):
    # 1. alias definitions get an ink sibling: --violet: var(--sindoor-57);  -> + --ink-violet: var(--ink-sindoor-57);
    def add_sib(m):
        name, tok = m.group(1), m.group(2)
        if name.startswith('--ink-'): return m.group(0)
        return '%s; --ink-%s: var(--ink-%s)' % (m.group(0), name[2:], tok)
    css = re.sub(r'(?<!ink-)(--[a-z][a-z0-9-]*)\s*:\s*var\(--(%s)\)(?![^;{}]*--ink-)' % TOK, lambda m: add_sib(m) if ('--ink-' + m.group(1)[2:] + ':') not in css else m.group(0), css)
    # 2. text declarations: direct tokens and known aliases -> ink
    def text_decl(m):
        prop, val = m.group(1), m.group(2)
        val = re.sub(r'var\(--(%s)(-rgb)?\)' % TOK, lambda v: 'var(--ink-%s%s)' % (v.group(1), v.group(2) or ''), val)
        val = re.sub(r'var\(--([a-z][a-z0-9-]*)\)', lambda v: 'var(--ink-%s)' % v.group(1) if ('--' + v.group(1)) in aliases else v.group(0), val)
        return prop + val
    css = re.sub(r'((?<![a-z-])(?:color|-webkit-text-fill-color|caret-color)\s*:\s*)([^;}"]+)', text_decl, css)
    # a label on its OWN fill (the same rule paints a background) reads against that fill, not the
    # page: keep (or restore) the brand colour there
    def own_fill(m):
        body = m.group(2)
        fills = re.findall(r'(?<![a-z-])background(?:-color)?\s*:\s*([^;}]+)', body)
        def solid(v):
            v = v.strip()
            if re.match(r'(transparent|none|inherit|initial)\b', v): return False
            alphas = [float(x) for x in re.findall(r'/\s*([0-9.]+)\s*\)', v)] + [float(x) for x in re.findall(r'rgba\([^)]*,\s*([0-9.]+)\s*\)', v)]
            return not alphas or max(alphas) >= 0.5      # a faint tint is not a fill; the page shows through
        if not any(solid(v) for v in fills): return m.group(0)
        body = re.sub(r'((?<![a-z-])(?:color|-webkit-text-fill-color)\s*:\s*)([^;}]+)', lambda d: d.group(1) + re.sub(r'var\(--ink-', 'var(--', d.group(2)), body)
        return m.group(1) + body + m.group(3)
    return re.sub(r'(\{)([^{}]*)(\})', own_fill, css)

def rewrite(path, fn):
    s = open(path, encoding='utf-8').read(); o = fn(s)
    if o != s: open(path, 'w', encoding='utf-8').write(o); print('  ink:', path)

base_aliases = alias_defs(open('assets/styles.css', encoding='utf-8').read())

rewrite('assets/styles.css', lambda s: css_ink(s, base_aliases))
for src in ('assets/home/src/home.html', 'assets/method/src/scene.html'):
    def f(s):
        al = dict(base_aliases); al.update(alias_defs(s))
        return re.sub(r'(<style[^>]*>)(.*?)(</style>)', lambda m: m.group(1) + css_ink(m.group(2), al) + m.group(3), s, flags=re.S)
    rewrite(src, f)
for page in sorted(glob.glob('*.html')):
    if page in ('index.html', 'methodology.html'): continue
    def pg(s):
        s = re.sub(r'(<style[^>]*>)(.*?)(</style>)', lambda m: m.group(1) + css_ink(m.group(2), base_aliases) + m.group(3), s, flags=re.S)
        return re.sub(r'(\sstyle=")([^"]*)(")', lambda m: m.group(1) + css_ink(m.group(2), base_aliases) + m.group(3), s)
    rewrite(page, pg)

# Tailwind textColor mirror
p = 'assets/tailwind-config.js'
s = open(p, encoding='utf-8').read()
s = re.sub(r'\n\s*// ink-textColor:start.*?// ink-textColor:end\n', '\n', s, flags=re.S)
m = re.search(r'\n(\s*)colors: \{(.*?)\n\1\},', s, re.S)
assert m, 'colors block not found'
body = re.sub(r'var\(--(%s)-rgb\)' % TOK, lambda v: 'var(--ink-%s-rgb)' % v.group(1), m.group(2))
body = re.sub(r'var\(--(%s)\)' % TOK, lambda v: 'var(--ink-%s)' % v.group(1), body)
block = '\n%s// ink-textColor:start — generated by tools/apply-ink.py; text uses ink, fills keep the brand colour\n%stextColor: {%s\n%s},\n%s// ink-textColor:end\n' % (m.group(1), m.group(1), body, m.group(1), m.group(1))
s = s[:m.end()] + block + s[m.end():].lstrip('\n')
open(p, 'w', encoding='utf-8').write(s)
print('  ink: tailwind textColor mirrored')
